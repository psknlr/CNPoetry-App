    lex = flat_lexicon()
    print(f"广谱意象 {len(lex)} 个 · 表面形式 {sum(len(v['surfaces']) for v in lex.values())} 条")
    for cat, items in IMAGERY_EXT.items():
        print(f"  {cat}：{len(items)} —— {' '.join(items)}")
