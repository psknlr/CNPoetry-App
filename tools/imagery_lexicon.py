def flat_lexicon() -> Dict[str, Dict]:
    """规范名 → {surfaces, category}；表面形式最长优先。"""
    out: Dict[str, Dict] = {}
    for cat, items in IMAGERY_EXT.items():
        for name, surfaces in items.items():
            s = sorted(set(surfaces), key=len, reverse=True)
            out[name] = {"surfaces": s, "category": cat}
    return out


def surface_pairs() -> List:
    """[(表面形式, 规范名)…]，按长度降序 —— 供最长优先匹配。"""
    pairs = [(s, name) for name, v in flat_lexicon().items() for s in v["surfaces"]]
    pairs.sort(key=lambda x: -len(x[0]))
    return pairs


